#!/usr/bin/env node
// The typed contract of a workspace package (LINE-MODULE (a)), generated from its package.json "exports": one
// `export * as <name> from '<target>'` per public subpath ("." re-exported flat), so the contract is exactly the
// public API the package exports, typed from the modules' own JSDoc, and never drifts from "exports".
//
//   node packages/tools/line-module/contracts.mjs            # (re)write <pkg>/contract.d.ts for every package with "exports"
//   node packages/tools/line-module/contracts.mjs --check    # exit 1 when a generated contract is missing or stale
//
// A package without "exports" (a CLI-only package such as packages/cli or packages/studio) keeps a hand-written
// contract.d.ts; this script leaves it alone. test/line-module-contracts.test.mjs runs the check.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { write } from '@line/construct-core/fs';

export const GENERATED_MARK = '// Generated by packages/tools/line-module/contracts.mjs from package.json "exports"; do not edit.';

const targetOf = (v) => (typeof v === 'string' ? v : v && typeof v === 'object' ? (v.types ?? v.import ?? v.default ?? null) : null);
const camel = (s) => s.replace(/[-/.]+([a-z0-9])/gi, (_, c) => c.toUpperCase()).replace(/^[^a-zA-Z_$]+/, '');

/**
 * The contract.d.ts source for a package.json, or null when it has no "exports" map.
 * @param {{name?: string, exports?: Record<string, unknown>}} pkg Parsed package.json.
 * @returns {string|null} The file's text.
 */
export function contractSource(pkg) {
  const exp = pkg.exports;
  if (!exp || typeof exp !== 'object' || Array.isArray(exp)) return null;
  const lines = [GENERATED_MARK, `// The typed contract of ${pkg.name}: every public entry its package.json "exports" lists, typed from the`, '// modules themselves. Import the package only through these entries (LINE-MODULE).', ''];
  for (const [key, value] of Object.entries(exp)) {
    const target = targetOf(value);
    if (!target || key === './package.json' || /\.json$/.test(target)) continue; // data, not an API
    const from = target.replace(/\.ts$/, ''); // a .ts entry is imported without its extension
    if (key === '.') lines.push(`export * from '${from}';`);
    else lines.push(`/** \`${pkg.name}${key.slice(1)}\` */`, `export * as ${camel(key.slice(2))} from '${from}';`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Every workspace package under packages/ whose contract.d.ts is generated, with its expected text.
 * @param {string} root Repo root.
 * @returns {{dir: string, file: string, expected: string, actual: string|null}[]} One entry per package with "exports".
 */
export function contractStatus(root) {
  const out = [];
  for (const d of readdirSync(join(root, 'packages')).sort()) {
    const pj = join(root, 'packages', d, 'package.json');
    if (!existsSync(pj)) continue;
    const expected = contractSource(JSON.parse(readFileSync(pj, 'utf8')));
    if (expected === null) continue;
    const file = join(root, 'packages', d, 'contract.d.ts');
    out.push({ dir: `packages/${d}`, file, expected, actual: existsSync(file) ? readFileSync(file, 'utf8') : null });
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const s of contractStatus(root)) {
    if (s.actual === s.expected) continue;
    if (s.actual !== null && !s.actual.startsWith(GENERATED_MARK)) { console.log(`skip   ${s.dir}/contract.d.ts (hand-written)`); continue; }
    stale++;
    if (check) console.log(`stale  ${s.dir}/contract.d.ts`);
    else { write(s.file, s.expected); console.log(`wrote  ${s.dir}/contract.d.ts`); }
  }
  if (check && stale) { console.log('run: node packages/tools/line-module/contracts.mjs'); process.exit(1); }
}
