// Generates the Atoms page: every Smith atom with its native JavaScript, its plain call and its Atomic English
// sentence, each as a real function the page can run on inputs drawn by Smith's own generators.
//
//   node bench/atoms/atoms-page/build.mjs
//
// Reads smith-functional (SMITH_DIR, default ~/Repositories/smith-functional): the catalog, the compiled dist/ and
// test/support/gens.mjs. Writes site/: smith-bundle.mjs (atoms + sentences + generators, via esbuild),
// forms.mjs (the generated functions) and index.html. Rerun after Smith changes and the page follows.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const smithDir = process.env.SMITH_DIR ?? join(process.env.HOME, 'Repositories/smith-functional');
const esbuild = process.env.ESBUILD ?? join(process.env.HOME, 'Repositories/construct-worktrees/import-v2-probe/node_modules/.bin/esbuild');
const site = join(here, 'site');
mkdirSync(site, { recursive: true });

// 1. The bundle: Smith's atoms, its sentence layer and its input generators.
writeFileSync(join(here, 'entry.mjs'), [
  '// Bundle entry: Smith\'s atoms, its sentence layer, and its own input generators, for the browser.',
  `export * as smith from '${join(smithDir, 'dist/index.js')}';`,
  `export * as fluent from '${join(smithDir, 'dist/fluent/index.js')}';`,
  `export { arb } from '${join(smithDir, 'test/support/gens.mjs')}';`,
  `export { default as fc } from '${join(smithDir, 'node_modules/fast-check/lib/fast-check.js')}';`,
  '',
].join('\n'));
if (!existsSync(esbuild)) throw new Error(`esbuild not found at ${esbuild}; set ESBUILD`);
execFileSync(esbuild, [join(here, 'entry.mjs'), '--bundle', '--format=esm', '--platform=browser', `--outfile=${join(site, 'smith-bundle.mjs')}`, '--log-level=warning'], { stdio: 'inherit' });

// 2. The generated functions: for every atom and every check set, the native form, the plain call and the sentence.
const catalog = JSON.parse(readFileSync(join(smithDir, 'src/atoms/catalog.json'), 'utf8'));
const SHORT = { list: 'xs', item: 'x', text: 's', separator: 'sep', pattern: 'p', replacement: 'r', compare: 'order', type: 'Type' };
const ENTRIES = ['checks', 'clones', 'text', 'list', 'when', 'chooses', 'matches', 'attempts', 'choose', 'match', 'attempt'];
const mentions = (source, name) => new RegExp(`(^|[^\\w.])${name}\\b`).test(source);
const isExpression = (params, source) => {
  try { new Function(...params, `return (${source});`); return true; } catch { return false; }
};

// A generated atom's check: the receiver (named as in its `js` form) comes first, then the parameters.
function fromGenerated(a) {
  const c = a.check;
  const params = c.params.map((p) => p.name);
  const js = a.js?.[0] ?? '';
  const owner = c.native?.owner ?? '';
  const receiver = c.receiver ? ((js.match(/[A-Za-z_$][\w$]*/g) ?? []).find((w) => w !== owner && !params.includes(w)) ?? 'value') : null;
  const all = c.receiver ? [{ name: receiver, gen: c.receiver, rest: false }, ...c.params] : c.params;
  return { params: all.map((p) => [p.name, p.gen]), rest: all.map((p) => Boolean(p.rest)), body: nativeBody(c, all) };
}

// The native JavaScript a generated atom stands for, the same shape as its wrapper in Smith's generated code:
// a copy-returning atom copies its receiver, calls the method on the copy and returns the copy.
function nativeBody(c, all) {
  const { kind, owner, member } = c.native;
  const names = all.map((p) => p.name);
  const spread = (list) => list.map((p) => (p.rest ? `...${p.name}` : p.name)).join(', ');
  const call = (target, list) => `${target}${member.startsWith('[') ? member : `.${member}`}(${spread(list)})`;
  const [recv, ...rest] = c.receiver ? all : [null, ...all];
  const COPY = { Array: (r) => `${r}.slice()`, Date: (r) => `new Date(${r}.getTime())`, Map: (r) => `new Map(${r})`, Set: (r) => `new Set(${r})` };
  switch (kind) {
    case 'instance': case 'inplace': return `return ${call(recv.name, rest)};`;
    case 'static': return `return ${call(owner, all)};`;
    case 'call': return `return ${owner}(${spread(all)});`;
    case 'construct': return `return new ${owner}(${spread(all)});`;
    case 'global': return `return ${call('globalThis', all)};`;
    case 'copy': return COPY[owner] ? `const copy = ${COPY[owner](recv.name)};\n  ${call('copy', rest)};\n  return copy;` : null;
    case 'copyReceiver': return `return ${call(`new ${owner}(${recv.name})`, rest)};`;
    case 'staticCopy': return `const copy = { ...${names[0]} };\n  ${owner}.${member}(copy${all.length > 1 ? `, ${spread(all.slice(1))}` : ''});\n  return copy;`;
    default: return null;
  }
}

const lines = [
  '// GENERATED by build.mjs from smith-functional\'s catalog. For every atom and check set: the native JavaScript,',
  '// the atom called plainly, and its Atomic English sentence, as functions the page runs side by side.',
  "import { smith, fluent } from './smith-bundle.mjs';",
  '',
  `const { ${ENTRIES.join(', ')} } = fluent;`,
  '',
  'export const forms = {',
];
const atoms = [];
let runnable = 0;
for (const a of catalog.atoms) {
  // Curated atoms list check sets; generated ones describe one call (`native`, `receiver`, `params`) to normalise.
  const sets = Array.isArray(a.check) ? a.check : a.check?.params ? [fromGenerated(a)] : [];
  const entry = { atom: a.atom, module: a.module, reads: a.reads, js: a.js ?? [], pure: a.pure, mutates: a.mutates, generated: Boolean(a.generated),
    verified: Boolean(a.verified), fluent: a.fluent ?? null, sets: [], why: '' };
  if (!sets.length) entry.why = a.verifiedBy ? `checked by a dedicated test (${a.verifiedBy})` : a.unverifiedReason ?? 'no generated inputs';
  const setLines = [];
  sets.forEach((set) => {
    const names = set.params.map(([n]) => n);
    const lazy = set.params.map(([, g]) => g.startsWith('lazy:'));
    const gens = set.params.map(([, g]) => g.replace(/^lazy:/, ''));
    const shorts = names.map((n) => SHORT[n] ?? n);
    const js = set.js?.[0] ?? a.js?.[0] ?? null;
    const blockOk = (body) => { try { new Function(...names, body); return true; } catch { return false; } };
    const native = set.body !== undefined
      ? (set.body && blockOk(set.body) ? `(${names.join(', ')}) => {\n  ${set.body}\n}` : null)
      : js && isExpression(names, js) ? `(${names.join(', ')}) => (${js})` : null;
    const plainArgs = names.map((n, k) => (lazy[k] ? `() => ${n}` : set.rest?.[k] ? `...${n}` : n));
    const plain = `(${names.join(', ')}) => smith.${a.atom}(${plainArgs.join(', ')})`;
    // A sentence may leave out the atom's trailing optional parameters; it then stands for the atom called without them.
    const used = a.fluent ? shorts.filter((n) => mentions(a.fluent, n)).length : 0;
    const sentence = a.fluent && used > 0 && shorts.slice(0, used).every((n) => mentions(a.fluent, n)) && isExpression([...ENTRIES, ...shorts], a.fluent)
      ? `(${shorts.join(', ')}) => (${a.fluent})` : null;
    const plainUsed = a.fluent && sentence ? used : names.length;
    entry.sets.push({ names, gens, lazy, used: plainUsed });
    // `plain` takes every argument and is what the native form is held to; `short` leaves out the trailing optional
    // arguments a sentence doesn't name, and is what the sentence is held to.
    const short = plainUsed < names.length ? `(${names.join(', ')}) => smith.${a.atom}(${plainArgs.slice(0, plainUsed).join(', ')})` : null;
    setLines.push(`    { native: ${native ?? 'null'}, plain: ${plain}, short: ${short ?? 'null'}, sentence: ${sentence ?? 'null'} },`);
  });
  if (setLines.length) {
    runnable++;
    lines.push(`  ${a.atom}: [`, ...setLines, '  ],');
  }
  atoms.push(entry);
}
lines.push('};', '');
writeFileSync(join(site, 'forms.mjs'), lines.join('\n'));

// 3. The page.
const stats = {
  atoms: atoms.length, sentences: atoms.filter((a) => a.fluent).length, runnable,
  modules: new Set(atoms.map((a) => a.module)).size, built: new Date().toISOString().slice(0, 16).replace('T', ' '),
};
const data = JSON.stringify({ stats, atoms }).replace(/</g, '\\u003c');
const template = readFileSync(join(here, 'template.html'), 'utf8');
writeFileSync(join(site, 'index.html'), template.replace('__DATA__', () => data));
console.log(`site/: ${stats.atoms} atoms (${stats.sentences} with a sentence, ${stats.runnable} runnable), ${stats.modules} modules`);
