// TR-23: give a real-rendered Subframe page the same `data-id` attribute page-preview.mjs's renderPreview()
// computes for the hand-authored plain-JSX examples (`value.x`, `list.x`, `list.sort`, `action.row.x` /
// `action.page.x`, `form.x`), so src/ui/demo.mjs's paintTree() — which colours `[data-id="..."]` elements by
// `data-part` — needs no changes to work over real component-rendered HTML. Injected as a literal JSX
// attribute *before* the page is compiled/rendered (see subframe-preview.mjs's Vite plugin), because
// Subframe's real components pass an unknown prop like `data-dyn` straight through to their root DOM
// element, but there is no template-context object at render time from which to compute "am I inside the
// list" the way page-preview.mjs's own recursive walk does — so the id is computed here, once, statically,
// from the same marker attributes and the same ancestry rule (nearest enclosing `data-list`/`<form>`).
import { parse } from "@babel/parser";
import _traverse from "@babel/traverse";
import _generate from "@babel/generator";
import * as t from "@babel/types";
import { attr } from "./extract.mjs";

const traverse = _traverse.default ?? _traverse;
const generate = _generate.default ?? _generate;

function parseTsx(source) {
  return parse(source, { sourceType: "module", plugins: ["jsx", "typescript"] });
}

function tagName(el) {
  const n = el.openingElement.name;
  return n.type === "JSXIdentifier" ? n.name : null;
}

function hasAncestor(path, test) {
  for (let p = path.parentPath; p; p = p.parentPath) if (p.isJSXElement() && test(p.node)) return true;
  return false;
}

/**
 * Add a `data-id` attribute to every marked element in a Subframe TSX page's source, using the same id
 * scheme as `page-preview.mjs`'s `render()`. A no-op on an element that already has one.
 *
 * @param {string} source The marked page's TSX source (already carrying `data-dyn`/`data-list`/`data-action`).
 * @returns {string} The source with `data-id` added (re-generated by `@babel/generator`, so formatting is
 *   not preserved — this output is only ever fed to Vite's SSR loader, never written back as the example's
 *   own page file).
 */
export function injectDataId(source) {
  const ast = parseTsx(source);
  traverse(ast, {
    JSXElement(path) {
      const el = path.node;
      if (attr(el, "data-id")) return;
      const dyn = attr(el, "data-dyn");
      const list = attr(el, "data-list");
      const action = attr(el, "data-action");
      const name = attr(el, "name");
      const tag = tagName(el);
      const inList = typeof list === "string" || hasAncestor(path, (n) => typeof attr(n, "data-list") === "string");
      let id = null;
      if (typeof list === "string") id = "list.sort";
      else if (typeof dyn === "string") id = inList ? `list.${dyn}` : `value.${dyn}`;
      else if (typeof action === "string") id = `action.${inList ? "row" : "page"}.${action}`;
      else if (
        ["input", "select", "textarea"].includes(tag) &&
        typeof name === "string" &&
        hasAncestor(path, (n) => tagName(n) === "form")
      )
        id = `form.${name}`;
      if (id) el.openingElement.attributes.push(t.jsxAttribute(t.jsxIdentifier("data-id"), t.stringLiteral(id)));
    },
  });
  return generate(ast, {}, source).code;
}

/** Quick check so callers only pay the parse+traverse cost on pages that actually carry markers. */
export function hasMarkers(source) {
  return /data-dyn=|data-list=|data-action=/.test(source);
}

/**
 * Add a `data-pm-src="line:col"` attribute to every HOST element (a plain lowercase JSX tag — never a
 * capitalized custom component like `Table.Row` or `Button`) in a Subframe TSX page's source. Stamped by
 * Trace itself (not Construct's `jsxSourceAnnotator`), so the rendered-Subframe overlay (LIN-197) works
 * without `CONSTRUCT_ROOT` set: `pagemap/inventory.mjs`'s `buildInventory` records the same 1-based
 * line and babel `loc.start.column + 1` for the same host element (pinned by
 * `pagemap/pagemap.test.mjs`'s "Construct's data-cx-src positions equal the Page map's node positions"
 * test), so a click on the rendered element resolves to the Page map's node id by construction, never a guess.
 * A no-op on an element that already has one.
 *
 * @param {string} source The page's TSX source.
 * @returns {string} The source with `data-pm-src` added (re-generated by `@babel/generator`).
 */
export function injectPmSrc(source) {
  const ast = parseTsx(source);
  traverse(ast, {
    JSXElement(path) {
      const el = path.node;
      const name = el.openingElement.name;
      if (name.type !== "JSXIdentifier" || !/^[a-z]/.test(name.name)) return;
      if (attr(el, "data-pm-src")) return;
      el.openingElement.attributes.push(
        t.jsxAttribute(t.jsxIdentifier("data-pm-src"), t.stringLiteral(`${el.loc.start.line}:${el.loc.start.column + 1}`))
      );
    },
  });
  return generate(ast, {}, source).code;
}
