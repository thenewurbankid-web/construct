// Line logic verification step 8: the L2 dev-server level (logicVerify/devServerRun.mjs) behind verifyPair's
// RUNNERS['dev-server']. A tiny fixture app (plain node:http, its own `dev` script) stands in for the target's dev
// server; a real `next dev` runs only through packages/tools/dev/heavy.sh, never here.
