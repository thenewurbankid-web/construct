const UNIT = { file: 'app/orders/page.js', fn: 'OrdersPage' };

// The app's server: renders /orders with the unit, answers everything else 404, exits on SIGTERM (so V8 writes the
// coverage, as next dev does).
const SERVER = `import http from 'node:http';
import { OrdersPage } from './app/orders/page.js';
const srv = http.createServer(async (req, res) => {
  if (req.url === '/orders') { const out = await OrdersPage(); res.writeHead(out.status ?? 200, out.headers ?? { 'content-type': 'text/html' }); res.end(out.html ?? ''); return; }
  res.writeHead(404); res.end('not found');
});
srv.listen(Number(process.env.PORT), '127.0.0.1');
process.on('SIGTERM', () => srv.close(() => process.exit(0)));
`;

const PAGE = (body) => `export async function OrdersPage() {
  const res = await fetch(process.env.ORDERS_API_URL + '/orders');
  const data = await res.json();
${body}
}
`;
const SAME = "  return { html: '<ul>' + data.items.map((o) => '<li>' + o.name + '</li>').join('') + '</ul><p>' + process.env.SHOP_NAME + '</p>' };";

/** One app root: package.json with a dev script, the server, the unit's page and a .env with a real-looking URL. */
function writeApp(root, page, { dev = 'node server.mjs' } = {}) {
  fs.mkdirSync(path.join(root, 'app/orders'), { recursive: true });
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'l2-fixture', private: true, type: 'module', scripts: { dev } }));
  fs.writeFileSync(path.join(root, 'server.mjs'), SERVER);
  fs.writeFileSync(path.join(root, UNIT.file), page);
  fs.writeFileSync(path.join(root, '.env'), 'ORDERS_API_URL=https://real.invalid\nSECRET_TOKEN=do-not-use\n');
}

function pair(beforePage, afterPage, opts = {}) {
  const top = makeTempDir('lv-devserver-test-');
  writeApp(path.join(top, 'before'), beforePage, opts);
  writeApp(path.join(top, 'after'), afterPage, opts);
  return { beforeRoot: path.join(top, 'before'), afterRoot: path.join(top, 'after') };
}

const FAST = { startupMs: 15_000, requestMs: 5_000, graceMs: 2_000 };

test('envKeysRead: keys from source (all three syntaxes) and .env names, reserved left out, never values', () => {
  const root = makeTempDir('lv-devserver-env-');
  fs.mkdirSync(path.join(root, 'src'));
  fs.mkdirSync(path.join(root, 'node_modules/x'), { recursive: true });
  fs.writeFileSync(path.join(root, 'src/a.ts'), "const a = process.env.API_BASE_URL; const b = process.env['FLAG']; const c = import.meta.env.VITE_HOST; const p = process.env.PORT;");
  fs.writeFileSync(path.join(root, 'node_modules/x/i.js'), 'process.env.IGNORED');
  fs.writeFileSync(path.join(root, '.env.local'), 'export DB_URI=postgres://x\nNODE_ENV=production\n# C=1\n');
  assert.deepEqual(envKeysRead(root), ['API_BASE_URL', 'DB_URI', 'FLAG', 'VITE_HOST']);
});

test('envLineStubs: URL-like keys get the fixture URL, the rest a sentinel by key order; the text is sorted dotenv', () => {
  const stubs = envLineStubs(['API_BASE_URL', 'FLAG', 'SHOP_NAME', 'VITE_HOST'], { fixtureUrl: 'http://127.0.0.1:9' });
  assert.deepEqual(stubs, { API_BASE_URL: 'http://127.0.0.1:9', FLAG: sentinel(42, 301), SHOP_NAME: sentinel(42, 302), VITE_HOST: 'http://127.0.0.1:9' });
  const text = formatEnvLine(stubs);
  assert.match(text, /^# Generated by Line/);
  assert.deepEqual(text.trim().split('\n').slice(1).map((l) => l.split('=')[0]), ['API_BASE_URL', 'FLAG', 'SHOP_NAME', 'VITE_HOST']);
});

